package com.moup.domain.workplace.domain;

/// 근무지(매장) 카테고리.
///
/// 예전에는 `category_name`에 화면 표시용 한글(`"편의점"`)이 그대로 저장됐다.
/// 구 iOS 클라이언트가 UI 텍스트를 그대로 주고받도록 짜여 있었기 때문이다.
///
/// 표시명을 DB에 두면 두 가지가 깨진다:
/// - 다국어 대응이 막힌다. 저장값이 곧 한국어 UI다.
/// - 클라이언트가 문구를 한 글자만 바꿔도 기존 데이터와 매칭되지 않는다.
///   실제로 iOS를 재구현하며 영문 코드로 파싱하게 했더니 기존 근무지의 카테고리를
///   읽지 못해 수정 화면 저장이 아예 막혔다.
///
/// **표시명은 클라이언트가 갖는다.** 서버는 코드만 저장·반환한다.
/// 아래 주석의 한글은 매핑 참고용이지 서버가 쓰는 값이 아니다.
public enum WorkplaceCategory {
    /// 음식점
    RESTAURANT,
    /// 카페
    CAFE,
    /// 편의점
    CVS,
    /// 영화관
    MOVIE_THEATER,
    /// 기타
    OTHERS
}
